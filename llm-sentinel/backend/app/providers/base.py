"""Provider-independent LLM interface and domain models."""

from abc import ABC, abstractmethod
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


# --- Custom Domain Exceptions ---

class LLMProviderError(Exception):
    """Base exception for all LLM provider failures."""

    def __init__(self, message: str, details: Optional[Dict[str, Any]] = None) -> None:
        super().__init__(message)
        self.message = message
        self.details = details or {}


class ProviderConfigError(LLMProviderError):
    """Raised when an LLM provider is misconfigured (e.g. missing API key)."""
    pass


class ProviderAPIError(LLMProviderError):
    """Raised when an upstream LLM API call fails."""
    pass


# --- Standard Data Models ---

class ProviderUsage(BaseModel):
    """Token usage metrics for an LLM response."""

    prompt_tokens: Optional[int] = Field(default=None, description="Number of tokens in prompt")
    completion_tokens: Optional[int] = Field(default=None, description="Number of tokens in completion")
    total_tokens: Optional[int] = Field(default=None, description="Total tokens consumed")


class ToolCallRequest(BaseModel):
    """Normalized tool call request generated by the LLM."""

    name: str = Field(..., description="Function/tool name to invoke")
    args: Dict[str, Any] = Field(default_factory=dict, description="Arguments dictionary")


class LLMResponse(BaseModel):
    """Standardized response from any LLM provider."""

    provider: str = Field(..., description="Provider name (e.g. gemini, claude)")
    model: str = Field(..., description="Model identifier used")
    response: str = Field(..., description="Generated text output")
    tool_calls: Optional[list[ToolCallRequest]] = Field(
        default=None, description="Tool/function calls requested by the model"
    )
    usage: Optional[ProviderUsage] = Field(default=None, description="Token usage details")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Additional provider metadata")


class ProviderStatus(BaseModel):
    """Operational status report for an LLM provider."""

    provider: str = Field(..., description="Provider name")
    model: str = Field(..., description="Model identifier")
    is_configured: bool = Field(..., description="Whether required credentials exist")
    status: str = Field(..., description="Operational status: ready, not_configured, connected, or error")
    details: Optional[str] = Field(default=None, description="Human-readable status details")


# --- Abstract Provider Interface ---

class LLMProvider(ABC):
    """Abstract base class defining the provider-independent LLM interface.

    Allows adding future providers (Claude, OpenAI, Ollama) without modifying
    the core security testing engine.
    """

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Unique identifier of the LLM provider."""
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Currently active model identifier."""
        pass

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Generate a response for the given prompt.

        Args:
            prompt: User message or security probe payload.
            system_instruction: Optional system instruction/guardrail.
            temperature: Sampling temperature (0.0 to 2.0).
            max_tokens: Maximum output tokens.
            **kwargs: Additional provider-specific parameters.

        Returns:
            LLMResponse: Standardized response object.

        Raises:
            ProviderConfigError: If provider lacks configuration or credentials.
            ProviderAPIError: If external API call fails.
        """
        pass

    @abstractmethod
    async def check_status(self) -> ProviderStatus:
        """Check configuration status without incurring API cost."""
        pass

    @abstractmethod
    async def test_connectivity(self) -> ProviderStatus:
        """Perform a live roundtrip probe to verify upstream credentials and reachability."""
        pass

